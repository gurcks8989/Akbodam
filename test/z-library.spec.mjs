import { test, expect } from '@playwright/test';
test('library folders, recent history and page bookmarks persist without changing setlists', async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  const before=await (await page.request.get('/api/state')).json();
  const pdf=before.scores.find(s=>s.title==='첫번째 악보');
  await page.locator('#library-open').click();
  await expect(page.locator('#library-dialog')).toHaveCSS('width','1280px');
  await page.locator('#folder-new').click();await page.locator('#folder-name').fill('주일 찬양');await page.locator('#folder-form button[type=submit]').click();
  await expect(page.locator('#library-heading')).toHaveText('주일 찬양');
  await page.locator('#library-all').click();
  const folder=await page.locator('#library-folders button').getAttribute('data-folder-filter');
  await page.locator(`[data-score-folder="${pdf.id}"]`).selectOption(folder);
  await page.locator('#library-folders button').click();
  await expect(page.locator('.library-row')).toHaveCount(1);
  await page.screenshot({path:'test-results/library-folders.png',fullPage:true});
  await page.locator('[data-view]').click();
  await expect(page.locator('#stage canvas')).toBeVisible();
  await page.locator('#nav-pages').click();
  await expect(page.locator('.page-thumbnail')).toHaveCount(2);
  await expect(page.locator('.page-thumbnail canvas').first()).toBeVisible();
  await page.locator('[data-jump-page="2"]').click();
  await expect(page.locator('#page-label')).toHaveText('2 / 2');
  await page.locator('#bookmark-page').click();
  await expect(page.locator('#bookmark-page')).toHaveAttribute('aria-pressed','true');
  await page.locator('#nav-bookmarks').click();
  await expect(page.locator('.page-thumbnail')).toHaveCount(1);
  await expect(page.locator('.page-thumbnail')).toHaveAttribute('data-jump-page','2');
  await page.screenshot({path:'test-results/page-bookmarks.png',fullPage:true});
  await page.reload();await expect(page.locator('#page-label')).toHaveText('2 / 2');
  await expect(page.locator('#bookmark-page')).toHaveAttribute('aria-pressed','true');
  await page.locator('#library-open').click();await page.locator('#library-recent').click();
  await expect(page.locator('.library-row').first().locator('strong')).toHaveText('첫번째 악보');
  await page.locator('#library-folders button').click();await expect(page.locator('.library-row')).toHaveCount(1);
  await page.setViewportSize({width:480,height:800});
  await page.screenshot({path:'test-results/library-mobile.png',fullPage:true});
  expect(await page.locator('.library-content').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBeTruthy();
  await page.locator('#folder-delete').click();await expect(page.locator('#library-folders button')).toHaveCount(0);
  await expect(page.locator('#library-heading')).toHaveText('미분류');
  await expect(page.locator(`[data-view="${pdf.id}"]`)).toBeVisible();
  await page.locator('#library-close').click();await page.locator('#bookmark-page').click();await expect(page.locator('#bookmark-page')).toHaveAttribute('aria-pressed','false');
  const after=await (await page.request.get('/api/state')).json();
  expect(after.playlists).toEqual(before.playlists);expect(after.scores).toHaveLength(before.scores.length);
  expect(errors).toEqual([]);
});
